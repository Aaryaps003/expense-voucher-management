
const fs = require("fs");
const path = require("path");
const Voucher = require("../models/Voucher");

// GET /api/vouchers/:id/signature/:type
const getVoucherSignature = async (req, res) => {
  try {
    const { id, type } = req.params;

    if (!["employee", "director"].includes(type)) {
      return res.status(400).json({
        message: "Signature type must be employee or director.",
      });
    }

    const voucher = await Voucher.findById(id);

    if (!voucher) {
      return res.status(404).json({
        message: "Voucher not found.",
      });
    }

    const role = req.user.role;
    const isOwner =
      voucher.employee.toString() === req.user._id.toString();

    // Employees can only access signatures on their own vouchers.
    if (role === "Employee" && !isOwner) {
      return res.status(403).json({
        message: "You cannot access this voucher.",
      });
    }

    // Only Director and Accounts may view other employees' vouchers.
    if (!["Employee", "Director", "Accounts"].includes(role)) {
      return res.status(403).json({
        message: "Access denied.",
      });
    }

    // An employee signature is available only to the voucher owner
    // or authorized staff. Director signatures follow the same rule.
    const filename =
      type === "employee"
        ? voucher.employeeSignature
        : voucher.directorSignature;

    if (!filename) {
      return res.status(404).json({
        message: "Signature not found.",
      });
    }

    // Filenames are generated by the upload middleware.
    // Reject path separators and traversal attempts.
    if (
      path.basename(filename) !== filename ||
      filename.includes("..")
    ) {
      return res.status(400).json({
        message: "Invalid signature filename.",
      });
    }

    const filePath = path.join(
      process.cwd(),
      "uploads",
      filename
    );

    if (!fs.existsSync(filePath)) {
      return res.status(404).json({
        message: "Signature file not found.",
      });
    }

    res.setHeader("Cache-Control", "private, no-store");
    res.setHeader("X-Content-Type-Options", "nosniff");

    return res.sendFile(filePath);
  } catch (error) {
    console.error("Get voucher signature error:", error.message);

    return res.status(500).json({
      message: "Failed to retrieve signature.",
    });
  }
};

module.exports = { getVoucherSignature };
